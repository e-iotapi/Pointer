// The shared production-shaped fixtures (test_env/fixtures/prod_shapes.json),
// used by T2 (both backtests' --export), T3 and T4 (loaded under the seed) and
// the mirror (combined with a synthetic set).
//
//   node tools/qa/fixtures.mjs build            # rebuild from the sources below
//   node tools/qa/fixtures.mjs check            # exit 1 if the committed file is stale
//   node tools/qa/fixtures.mjs out <rules|app|jsonl> <path>
//        rules: flat {path: data} for tools/backtest/rules --export
//        app:   flat {path: data} ({"$ts": ms}) for tools/backtest/app --export
//        jsonl: <path>/docs.jsonl, the prod_mirror format, for load.mjs / combine.mjs
//
// Sources, in order (a later one wins on the same path):
//   tools/backtest/rules/fixtures/prod_shapes.json  hand-copied stable write shapes
//   tools/backtest/app/fixtures/old_app_docs.json   written by the STABLE app's own
//                                                   encoders (each T2 app run refreshes it)
//   tools/backtest/app/fixtures/hand_docs.json      shapes no harness encoder writes
// Timestamps in the shared file: {"$ts": days from now} or {"$tsMs": epoch ms}.
// Bump VERSION when a consumer must change with the file (a field's meaning or
// the timestamp encoding), not for added documents.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = 1;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const FILE = path.join(root, 'test_env/fixtures/prod_shapes.json');
const read = (p) => JSON.parse(readFileSync(path.join(root, p), 'utf8'));

// The app fixtures' {"$ts": ms} is absolute; the shared file says $tsMs.
const appTs = (v) => {
  if (Array.isArray(v)) return v.map(appTs);
  if (v && typeof v === 'object') {
    if (Object.keys(v).length === 1 && typeof v.$ts === 'number') return { $tsMs: v.$ts };
    return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, appTs(x)]));
  }
  return v;
};
const dropComment = ({ _comment, ...rest }) => rest;

export function build() {
  const docs = {
    ...read('tools/backtest/rules/fixtures/prod_shapes.json').docs,
    ...appTs(dropComment(read('tools/backtest/app/fixtures/old_app_docs.json'))),
    ...appTs(dropComment(read('tools/backtest/app/fixtures/hand_docs.json'))),
  };
  const sorted = Object.fromEntries(Object.keys(docs).sort().map((k) => [k, docs[k]]));
  return { version: VERSION, _comment: 'Generated by tools/qa/fixtures.mjs build; do not edit (edit its sources).', docs: sorted };
}

// Resolves the shared encodings against [now] for one consumer.
function resolve(v, ts) {
  if (Array.isArray(v)) return v.map((x) => resolve(x, ts));
  if (v && typeof v === 'object') {
    if ('$ts' in v) return ts(Math.round(Date.now() + v.$ts * 864e5));
    if ('$tsMs' in v) return ts(v.$tsMs);
    return Object.fromEntries(Object.entries(v).filter(([, x]) => !(x && typeof x === 'object' && '$delete' in x)).map(([k, x]) => [k, resolve(x, ts)]));
  }
  return v;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const [cmd, fmt, out] = process.argv.slice(2);
  const text = (o) => JSON.stringify(o, null, 1) + '\n';
  if (cmd === 'build') {
    mkdirSync(path.dirname(FILE), { recursive: true });
    writeFileSync(FILE, text(build()));
    console.log(`wrote ${path.relative(root, FILE)} (${Object.keys(build().docs).length} docs, v${VERSION})`);
  } else if (cmd === 'check') {
    if (readFileSync(FILE, 'utf8') !== text(build())) { console.error('test_env/fixtures/prod_shapes.json is stale: node tools/qa/fixtures.mjs build'); process.exit(1); }
  } else if (cmd === 'out' && out) {
    const { version, docs } = JSON.parse(readFileSync(FILE, 'utf8'));
    if (version !== VERSION) throw new Error(`prod_shapes.json is v${version}, this tool reads v${VERSION}`);
    if (fmt === 'rules') writeFileSync(out, JSON.stringify(Object.fromEntries(Object.entries(docs).map(([k, d]) => [k, resolve(d, (ms) => ({ $tsMs: ms }))]))));
    else if (fmt === 'app') writeFileSync(out, JSON.stringify(Object.fromEntries(Object.entries(docs).map(([k, d]) => [k, resolve(d, (ms) => ({ $ts: ms }))]))));
    else if (fmt === 'jsonl') {
      mkdirSync(out, { recursive: true });
      const ts = (ms) => ({ __t: 'ts', s: Math.floor(ms / 1000), n: (ms % 1000) * 1e6 });
      writeFileSync(path.join(out, 'docs.jsonl'), Object.entries(docs).map(([p, d]) => JSON.stringify({ path: p, data: resolve(d, ts) })).join('\n') + '\n');
    } else throw new Error(`unknown format ${fmt}`);
  } else {
    console.error('usage: fixtures.mjs build | check | out <rules|app|jsonl> <path>');
    process.exit(2);
  }
}
